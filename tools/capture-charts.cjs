// Vérifie les interactions des graphiques et capture l'écran (mêmes prérequis que capture-extra.cjs).
const { chromium } = require('playwright')
const B = 'http://127.0.0.1:5173'
const OUT = require('path').join(__dirname, '..', 'docs', 'screenshots')
const H = { 'X-Requested-With': 'mysuite', 'Content-Type': 'application/json' }
const assert = (c, m) => { if (!c) throw new Error('ASSERT ' + m); console.log('ok:', m) }
;(async () => {
  const b = await chromium.launch()
  const c = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })
  const r = await c.request.post(B + '/api/v1/auth/login', { headers: H, data: { email: 'rh@demo.test', password: 'Demo-Passw0rd-2026' } })
  assert(r.ok(), 'login')
  const p = await c.newPage()
  const errors = []; p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  await p.goto(B + '/'); await p.waitForSelector('text=Répartition de l\'effectif')
  await p.waitForSelector('[role=img] svg')
  const total = await p.textContent('div.relative.h-56 span.text-2xl')
  await p.hover('button:has-text("Test") >> nth=0').catch(() => {})
  const first = p.locator('ul.space-y-1 button').first()
  await first.hover()
  const hovered = await p.textContent('div.relative.h-56 span.text-xs')
  assert(hovered.includes('%'), 'survol anneau affiche un pourcentage (' + hovered + ')')
  await p.click('role=radio[name="Site"]'); await p.waitForTimeout(400)
  assert((await p.locator('ul.space-y-1 button').count()) > 0, 'changement de dimension')
  await p.click('role=radio[name="Département"]')
  await first.hover(); await p.waitForTimeout(300)
  await p.screenshot({ path: OUT + '/18-graphique-anneau.png' })
  await p.click('role=radio[name="Barres"]'); await p.waitForSelector('.recharts-bar-rectangle path'); await p.waitForTimeout(500)
  await p.screenshot({ path: OUT + '/19-graphique-barres.png' })

  await p.goto(B + '/reports'); await p.waitForSelector('.recharts-bar-rectangle path')
  await p.click('role=radio[name="Courbe"]'); await p.waitForSelector('.recharts-line'); assert(true, 'bascule en courbe')
  await p.click('role=radio[name="Barres"]'); await p.waitForSelector('.recharts-bar-rectangle path')
  const n0 = await p.locator('.recharts-bar').count()
  await p.click('button[aria-pressed]:has-text("Sorties")'); await p.waitForTimeout(400)
  const n1 = await p.locator('.recharts-bar').count()
  assert(n1 < n0, `masquer une série via la légende (${n0} -> ${n1})`)
  await p.click('button[aria-pressed]:has-text("Sorties")'); await p.waitForTimeout(400)
  assert((await p.locator('.recharts-bar').count()) === n0, 'réafficher la série')
  const box = await p.locator('.recharts-bar-rectangle path').first().boundingBox()
  await p.mouse.click(box.x + box.width / 2, box.y + box.height / 2); await p.waitForTimeout(400)
  assert(await p.locator('[role=status]').first().isVisible(), 'clic sur un point affiche le détail')
  await p.mouse.move(box.x + box.width / 2 + 60, box.y + box.height / 2); await p.waitForTimeout(300)
  await p.screenshot({ path: OUT + '/20-rapports-interactif.png', fullPage: true })
  console.log('erreurs console:', errors.length ? errors.slice(0, 3) : 'aucune')
  await b.close()
})().catch((e) => { console.log('FAIL', e.message.slice(0, 400)); process.exit(1) })
